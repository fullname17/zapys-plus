/// Легкий шар перекладу. Ключ — українське джерело (uk = identity), тож
/// невимкнені рядки безпечно показують українською. Реактивність: gLang
/// встановлюється в KavioApp з локалі, а MaterialApp має key(gLang) — при зміні
/// мови все дерево перебудовується й t() повертає нову мову.
String gLang = 'uk';

String t(String uk) {
  if (gLang == 'uk') return uk;
  final m = gLang == 'en' ? _en : _ru;
  return m[uk] ?? uk;
}

/// З підстановкою {n}/{name} тощо.
/// Відмінювання числівників: 1 послуга, 3 послуги, 5 послуг.
///
/// Форми передаються українською й перекладаються звичайним [t], тож словники
/// EN/RU лишаються тим самим «ключ = український оригінал».
String tn(int n, String one, String few, String many) {
  final mod10 = n % 10;
  final mod100 = n % 100;
  if (mod10 == 1 && mod100 != 11) return t(one);
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return t(few);
  return t(many);
}

String tp(String uk, Map<String, Object> args) {
  var s = t(uk);
  args.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
  return s;
}

